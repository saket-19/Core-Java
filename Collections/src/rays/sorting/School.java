package rays.sorting;

import java.util.*;

public class School {
	public String name;
	public int rollno;
	public int marks;
    
	public School(String name,int rollno,int marks) {
		this.name=name;
		this.rollno=rollno;
		this.marks=marks;
		
	}
	public String toString() {
		return "name: " +name +" rollno: "+rollno +" marks: "+marks;
	}
	
	
		
	}

